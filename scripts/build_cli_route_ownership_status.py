#!/usr/bin/env python3
"""Render and check CLI route ownership status sections from the ownership matrix."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any


CLI_PREFIX = "/api/ideliumcl"
BEGIN = "<!-- BEGIN GENERATED: cli-route-ownership -->"
END = "<!-- END GENERATED: cli-route-ownership -->"

# Explicit route state derived from the matrix owner and aggregate rollout state.
# "implemented" means Go code exists and the matrix records Go as the target
# owner, but production traffic is still routed to Laravel.
GO_STATES = {
    "laravel-primary": "implemented",
    "shadow": "shadow",
    "canary": "canary",
    "go-primary": "owned",
}

STATE_DEFINITIONS = [
    ("laravel", "Laravel serves the route; no Go implementation is recorded."),
    ("implemented", "Go implementation exists; Laravel still serves production traffic."),
    ("shadow", "Go is compared against Laravel without serving responses."),
    ("canary", "Go serves a bounded share of traffic with Laravel fallback."),
    ("owned", "Go serves all traffic; Laravel is rollback-only."),
]


def route_state(route: dict[str, Any], rollout_states: dict[str, str]) -> str:
    aggregate = route["aggregate"]
    rollout = rollout_states[aggregate]
    if route["owner"] == "laravel":
        return "laravel"
    if route["owner"] == "go" and rollout in GO_STATES:
        return GO_STATES[rollout]
    raise ValueError(
        f"Unsupported owner/rollout combination for {route['route_id']}: "
        f"{route['owner']}/{rollout}."
    )


def render_section(matrix: dict[str, Any]) -> str:
    rollout_states = {a["aggregate"]: a["rollout_state"] for a in matrix["aggregates"]}
    routes = [r for r in matrix["routes"] if r["path"].startswith(CLI_PREFIX)]
    if not routes:
        raise ValueError("The ownership matrix contains no CLI routes.")
    states = {route["route_id"]: route_state(route, rollout_states) for route in routes}
    counts: dict[str, int] = {}
    for state in states.values():
        counts[state] = counts.get(state, 0) + 1

    lines = [
        BEGIN,
        "<!-- Generated by scripts/build_cli_route_ownership_status.py; do not edit. -->",
        "",
        f"CLI route ownership status ({len(routes)} routes), generated from the",
        "`docs/contracts/migration-ownership-matrix.json`:",
        "",
        "| State | Meaning | Routes |",
        "| --- | --- | ---: |",
    ]
    for name, meaning in STATE_DEFINITIONS:
        lines.append(f"| `{name}` | {meaning} | {counts.get(name, 0)} |")
    lines.extend(
        [
            "",
            "| Method | Path | Aggregate | Matrix owner | Rollout | State |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
    )
    for route in routes:
        lines.append(
            f"| `{route['method']}` | `{route['path']}` | `{route['aggregate']}` | "
            f"{route['owner']} | {rollout_states[route['aggregate']]} | "
            f"`{states[route['route_id']]}` |"
        )
    lines.append(END)
    return "\n".join(lines)


def replace_section(text: str, section: str, path: Path) -> str:
    start = text.find(BEGIN)
    end = text.find(END)
    if start == -1 or end == -1 or end < start:
        raise ValueError(f"{path} must contain the generated section markers.")
    return text[:start] + section + text[end + len(END):]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--matrix", type=Path, default=Path("docs/contracts/migration-ownership-matrix.json"))
    parser.add_argument("--target", type=Path, action="append", default=None)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    targets = args.target or [Path("README.md"), Path("docs/migration/progress.md")]

    matrix = json.loads(args.matrix.read_text(encoding="utf-8"))
    section = render_section(matrix)
    drift = False
    for target in targets:
        current = target.read_text(encoding="utf-8")
        updated = replace_section(current, section, target)
        if updated == current:
            continue
        if args.check:
            print(f"{target} diverges from the ownership matrix; regenerate it.", file=sys.stderr)
            drift = True
        else:
            target.write_text(updated, encoding="utf-8")
    return 1 if drift else 0


if __name__ == "__main__":
    raise SystemExit(main())
